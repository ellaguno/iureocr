export const dictionaries: Record<Lang, Record<Key, string>> = { en, es };

/** Idioma actual (reactivo). Inglés hasta que el backend diga otra cosa. */
export const i18n = $state({ lang: "en" as Lang });

type Params = Record<string, string | number>;

function format(text: string, params?: Params): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

/** Texto traducido con interpolación `{nombre}`. */
export function t(key: Key, params?: Params): string {
  return format(dictionaries[i18n.lang][key] ?? en[key] ?? key, params);
}

type PluralBase = Key extends infer K ? (K extends `${infer B}_one` ? B : never) : never;

/** Plural sencillo: `<base>_one` si n === 1, si no `<base>_other`. `{n}` se rellena solo. */
export function tn(base: PluralBase, n: number, params?: Params): string {
  const key = `${base}_${n === 1 ? "one" : "other"}` as Key;
  return t(key, { n, ...params });
}

/** Configuración regional para fechas y números. */
export function locale(): string {
  return i18n.lang === "es" ? "es-MX" : "en-US";
}

/** Nombre visible de un idioma de Tesseract (`spa`, `eng`…); los desconocidos, tal cual. */
export function ocrLangName(code: string): string {
  const key = `ocrLang.${code}` as Key;
  return key in en ? t(key) : code;
}

/** Pide al backend el idioma resuelto y lo aplica a toda la interfaz. */
export async function syncLanguage(): Promise<void> {
  try {
    i18n.lang = (await api.uiLanguage()) === "es" ? "es" : "en";
  } catch {
    i18n.lang = "en";
  }
  document.documentElement.lang = i18n.lang;
}
